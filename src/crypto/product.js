/**
 * Product Cipher Cryptographic Engine
 *
 * Mathematical Formulation:
 * -------------------------
 * A product cipher combines multiple cryptographic transformations sequentially
 * to enhance cryptographic strength through iterated rounds of confusion and diffusion.
 *
 * For CryptoBreak Lab, the Product Cipher is defined as a sequential composition
 * of classical transformations:
 *
 * Encryption Pipeline:
 *   Plaintext (P)
 *      │
 *      ▼
 *   Caesar Cipher:      T = Caesar(P, shift)
 *      │
 *      ▼
 *   Intermediate Text (T)
 *      │
 *      ▼
 *   Affine Cipher:      C = Affine(T, a, b)
 *      │
 *      ▼
 *   Final Ciphertext (C)
 *
 * Effective Function: C = Affine(Caesar(P))
 *
 * Decryption Pipeline (Inverse Order):
 *   Because the product cipher is a composition of transformations,
 *   decryption applies the inverse transformations in REVERSE order:
 *
 *   Ciphertext (C)
 *      │
 *      ▼
 *   Affine Decryption:  T = Affine⁻¹(C, a, b)
 *      │
 *      ▼
 *   Intermediate Text (T)
 *      │
 *      ▼
 *   Caesar Decryption:  P = Caesar⁻¹(T, shift)
 *      │
 *      ▼
 *   Recovered Plaintext (P)
 *
 * Effective Function: P = Caesar⁻¹(Affine⁻¹(C))
 */

import { encrypt as encryptCaesar, decrypt as decryptCaesar } from "./caesar.js";
import { encrypt as encryptAffine, decrypt as decryptAffine, isValidAffineKey } from "./affine.js";

/**
 * Computes the intermediate text generated by the first layer (Caesar Cipher).
 *
 * @param {string} text - Plaintext to transform
 * @param {number|string} caesarShift - Caesar shift key
 * @returns {string} Intermediate text after Caesar encryption
 */
export function getIntermediate(text, caesarShift) {
  return encryptCaesar(text, caesarShift);
}

/**
 * Encrypts plaintext using the sequential Product Cipher:
 * 1. Caesar Cipher transformation
 * 2. Affine Cipher transformation
 *
 * @param {string} text - Plaintext to encrypt
 * @param {number|string} caesarShift - Caesar shift key
 * @param {number|string} a - Affine multiplicative key (must be coprime to 26)
 * @param {number|string} b - Affine additive key
 * @returns {string} Final ciphertext
 */
export function encrypt(text, caesarShift, a, b) {
  if (typeof text !== "string") return "";

  // Step 1: Caesar transformation
  const intermediate = encryptCaesar(text, caesarShift);

  // Step 2: Affine transformation
  return encryptAffine(intermediate, a, b);
}

/**
 * Decrypts ciphertext using the inverse sequential Product Cipher:
 * 1. Affine Decryption (reverse layer 2)
 * 2. Caesar Decryption (reverse layer 1)
 *
 * @param {string} text - Ciphertext to decrypt
 * @param {number|string} caesarShift - Caesar shift key
 * @param {number|string} a - Affine multiplicative key
 * @param {number|string} b - Affine additive key
 * @returns {string} Recovered plaintext
 */
export function decrypt(text, caesarShift, a, b) {
  if (typeof text !== "string") return "";

  // Step 1 (Reverse of Affine layer): Affine decryption
  const intermediate = decryptAffine(text, a, b);

  // Step 2 (Reverse of Caesar layer): Caesar decryption
  return decryptCaesar(intermediate, caesarShift);
}

export { isValidAffineKey };
